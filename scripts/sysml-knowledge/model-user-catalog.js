function claimSearchTerms(id, subjectNodeId, objectNodeId, predicate) {
  const identifiers = [id, subjectNodeId, objectNodeId, predicate].filter(Boolean).flatMap((value) => {
    const local = String(value).replace(/^.*:/, '');
    const words = local.replace(/([a-z0-9])([A-Z])/g, '$1 $2').replace(/[_-]+/g, ' ');
    const root = local.replace(/(Definition|Usage|Relationship)$/u, '');
    return [local, words, root];
  });
  if (subjectNodeId === 'sysml20:AssignmentActionUsage') identifiers.push('AssignAction', 'AssignmentAction', 'Assign Action', 'Assignment Action');
  if (subjectNodeId === 'sysml20:RequirementDefinition' || subjectNodeId === 'sysml20:RequirementUsage') identifiers.push('Requirement');
  return [...new Set(identifiers.filter(Boolean))];
}

